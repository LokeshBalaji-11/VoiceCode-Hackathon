"""
Core Pydantic Schemas for VoiceCode Autopilot.
Defines the strict JSON contract for specs, patches, and execution logs.
"""
from pydantic import BaseModel, Field


class CodingSpec(BaseModel):
    """Spec extracted from user voice or text input."""
    goal: str = Field(description="Clear summary of what code change is requested.")
    files_hint: list[str] = Field(description="List of target files to inspect or modify.")
    acceptance_criteria: list[str] = Field(description="List of checks to verify the change.")


class FilePatch(BaseModel):
    """Structured code edit block generated by the LLM."""
    file_path: str = Field(description="Relative path of the file to modify.")
    search_block: str = Field(description="Exact existing code block to search for and replace.")
    replace_block: str = Field(description="New code block to insert.")
    explanation: str = Field(description="Brief reason for this specific code edit.")


class AgentResponse(BaseModel):
    """Complete patch plan generated by the LLM."""
    plan_summary: str = Field(description="Plain-English explanation of the changes.")
    patches: list[FilePatch] = Field(description="List of precise file edits.")